import { createHash } from 'node:crypto';
import { basename, join } from 'node:path';
import { isDeepStrictEqual } from 'node:util';
import { parse, stringify, type TomlTable, type TomlValue } from 'smol-toml';
import type { ContentLevel } from '../../core/contracts.ts';
import { localAbsolutePath } from '../../storage/local-path.ts';
import { pathKey } from '../../distribution/paths.ts';
import { contentAccessProfile } from './content-access.ts';

export interface PortableConfigOptions {
  root: string;
  node: string;
  entry: string;
  connectionPath: string;
  contentLevel: ContentLevel;
}

export interface PortableConfigPatch {
  operation: 'append' | 'repoint' | 'unchanged';
  serverName: 'anysearch' | 'anysearch_public_text';
  originalSha256: string;
  resultSha256: string;
  beforeText: string;
  afterText: string;
  server: TomlTable;
}

function fail(code: string): never { throw new Error(code); }
function table(value: TomlValue | undefined): value is TomlTable {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
    && [null, Object.prototype].includes(Object.getPrototypeOf(value));
}
function document(text: string): TomlTable {
  try { return parse(text.replace(/^\uFEFF/u, ''), { integersAsBigInt: 'asNeeded', unsafeKeyBehaviour: 'throw' }); }
  catch { return fail('RELEASE_CODEX_CONFIG_INVALID'); }
}
function hash(text: string): string { return createHash('sha256').update(text, 'utf8').digest('hex'); }
function samePath(left: unknown, right: string): boolean {
  if (typeof left !== 'string') return false;
  try { return pathKey(localAbsolutePath(left)) === pathKey(localAbsolutePath(right)); }
  catch { return false; }
}
function block(serverName: string, server: TomlTable, newline: string): string {
  return stringify({ mcp_servers: { [serverName]: server } }).replaceAll('\n', newline);
}

function requirePriorServer(value: TomlValue | undefined, connectionPath: string): TomlTable {
  if (!table(value) || typeof value.command !== 'string' || typeof value.cwd !== 'string'
    || !Array.isArray(value.args)) fail('RELEASE_CODEX_SERVER_CONFLICT');
  const args = value.args;
  const legacy = args.length === 3 && args[1] === '--connection';
  const portable = args.length === 4 && args[0] === '--no-global-search-paths' && args[2] === '--connection';
  const entry = legacy ? args[0] : args[1];
  const connection = legacy ? args[2] : args[3];
  if ((!legacy && !portable) || !samePath(connection, connectionPath)
    || !samePath(entry, join(value.cwd, legacy ? 'dist/mcp/main.cjs' : 'dist/release/mcp-entry.cjs'))
    || !samePath(value.command, value.command) || basename(value.command).toLowerCase() !== 'node.exe'
    || (portable && !samePath(value.command, join(value.cwd, 'runtime/node/node.exe')))) {
    fail('RELEASE_CODEX_SERVER_CONFLICT');
  }
  const expected: TomlTable = {
    command: value.command, args, cwd: value.cwd, enabled: true, enabled_tools: ['search', 'read'],
    default_tools_approval_mode: 'prompt',
    tools: { search: { approval_mode: 'approve' }, read: { approval_mode: 'approve' } },
  };
  if (value.env !== undefined) expected.env = { NODE_OPTIONS: '', NODE_PATH: '' };
  if ((portable && value.env === undefined) || !isDeepStrictEqual(value, expected, { skipPrototype: true })) {
    fail('RELEASE_CODEX_SERVER_CONFLICT');
  }
  return expected;
}

// Only the canonical block previously generated by AnySearch may be replaced.
export function createPortableConfigPatch(originalText: string, options: PortableConfigOptions): PortableConfigPatch {
  const { serverName } = contentAccessProfile(options.contentLevel);
  const before = document(originalText);
  const servers = before.mcp_servers;
  if (servers !== undefined && !table(servers)) fail('RELEASE_CODEX_SERVER_CONFLICT');
  const server: TomlTable = {
    command: options.node,
    args: ['--no-global-search-paths', options.entry, '--connection', options.connectionPath],
    cwd: options.root, enabled: true, enabled_tools: ['search', 'read'], default_tools_approval_mode: 'prompt',
    tools: { search: { approval_mode: 'approve' }, read: { approval_mode: 'approve' } },
    env: { NODE_OPTIONS: '', NODE_PATH: '' },
  };
  const newline = originalText.includes('\r\n') ? '\r\n' : '\n';
  const afterBlock = block(serverName, server, newline);
  let beforeText = '';
  let afterText = afterBlock;
  let operation: PortableConfigPatch['operation'] = 'append';
  let content: string;
  if (servers && Object.hasOwn(servers, serverName)) {
    const prior = requirePriorServer(servers[serverName], options.connectionPath);
    beforeText = block(serverName, prior, newline);
    const offset = originalText.indexOf(beforeText);
    if (offset < 0 || (offset > 0 && originalText[offset - 1] !== '\n')
      || originalText.indexOf(beforeText, offset + beforeText.length) !== -1) {
      fail('RELEASE_CODEX_NONCANONICAL_SECTION');
    }
    operation = isDeepStrictEqual(prior, server, { skipPrototype: true }) ? 'unchanged' : 'repoint';
    content = originalText.slice(0, offset) + afterBlock + originalText.slice(offset + beforeText.length);
  } else {
    const separator = originalText.length === 0 ? '' : originalText.endsWith('\n') ? newline : newline + newline;
    afterText = separator + afterBlock;
    content = originalText + afterText;
  }
  const expected = { ...before, mcp_servers: { ...servers, [serverName]: server } };
  if (!isDeepStrictEqual(document(content), expected, { skipPrototype: true })) fail('RELEASE_CODEX_PATCH_UNSAFE');
  if (Buffer.byteLength(beforeText) > 32_768 || Buffer.byteLength(afterText) > 32_768) fail('RELEASE_CODEX_BLOCK_TOO_LARGE');
  return { operation, serverName, originalSha256: hash(originalText), resultSha256: hash(content),
    beforeText, afterText, server };
}
