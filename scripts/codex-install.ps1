#requires -Version 7.2
<#
Apply only a reviewed plan generated by AnySearch. A plan authorizes an append
to its one config.toml target, not a generic TOML rewrite. Never hand-edit it.
Without -Apply this script validates and previews without writing anything.
#>
param(
  [Parameter(Mandatory = $true)][string]$PlanPath,
  [switch]$Apply
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$maximumPlanBytes = 65536
$maximumConfigBytes = 8388608
$maximumAppendBytes = 32768
$utf8 = [System.Text.UTF8Encoding]::new($false, $true)

function Get-Sha256([byte[]]$Bytes) {
  $algorithm = [System.Security.Cryptography.SHA256]::Create()
  try { return [System.Convert]::ToHexString($algorithm.ComputeHash($Bytes)).ToLowerInvariant() }
  finally { $algorithm.Dispose() }
}

function Get-CheckedFilePath([string]$Path) {
  if (-not [System.IO.Path]::IsPathFullyQualified($Path) -or $Path -match '[\x00-\x1f\x7f]') {
    throw 'CODEX_INSTALL_INVALID_PATH'
  }
  $fullPath = [System.IO.Path]::GetFullPath($Path)
  $item = Get-Item -LiteralPath $fullPath -Force
  if ($item.PSIsContainer) { throw 'CODEX_INSTALL_INVALID_PATH' }
  $ancestor = $item
  while ($null -ne $ancestor) {
    if (($ancestor.Attributes -band [System.IO.FileAttributes]::ReparsePoint) -ne 0) {
      throw 'CODEX_INSTALL_REPARSE_PATH'
    }
    if ($ancestor -is [System.IO.FileInfo]) { $ancestor = $ancestor.Directory }
    else { $ancestor = $ancestor.Parent }
  }
  return $fullPath
}

function Read-StreamBytes([System.IO.FileStream]$Stream, [long]$Maximum) {
  if ($Stream.Length -gt $Maximum) { throw 'CODEX_INSTALL_TOO_LARGE' }
  $bytes = [byte[]]::new([int]$Stream.Length)
  $Stream.Position = 0
  $offset = 0
  while ($offset -lt $bytes.Length) {
    $read = $Stream.Read($bytes, $offset, $bytes.Length - $offset)
    if ($read -le 0) { throw 'CODEX_INSTALL_SHORT_READ' }
    $offset += $read
  }
  return ,$bytes
}

function Read-Plan([string]$Path) {
  $checked = Get-CheckedFilePath $Path
  $file = [System.IO.File]::Open($checked, [System.IO.FileMode]::Open, [System.IO.FileAccess]::Read, [System.IO.FileShare]::Read)
  try { $bytes = Read-StreamBytes $file $maximumPlanBytes }
  finally { $file.Dispose() }
  $document = $null
  try {
    $document = [System.Text.Json.JsonDocument]::Parse($utf8.GetString($bytes))
    $root = $document.RootElement
    if ($root.ValueKind -ne [System.Text.Json.JsonValueKind]::Object) { throw 'CODEX_INSTALL_INVALID_PLAN' }
    $allowed = @('version', 'configPath', 'originalSha256', 'resultSha256', 'appendedText')
    $names = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
    foreach ($property in $root.EnumerateObject()) {
      if ($property.Name -cnotin $allowed -or -not $names.Add($property.Name)) { throw 'CODEX_INSTALL_INVALID_PLAN' }
    }
    if ($names.Count -ne $allowed.Count) { throw 'CODEX_INSTALL_INVALID_PLAN' }
    if ($root.GetProperty('version').ValueKind -ne [System.Text.Json.JsonValueKind]::Number -or $root.GetProperty('version').GetInt32() -ne 1) {
      throw 'CODEX_INSTALL_INVALID_PLAN'
    }
    $plan = @{}
    foreach ($key in $allowed | Where-Object { $_ -ne 'version' }) {
      $value = $root.GetProperty($key)
      if ($value.ValueKind -ne [System.Text.Json.JsonValueKind]::String) { throw 'CODEX_INSTALL_INVALID_PLAN' }
      $plan[$key] = $value.GetString()
    }
    if ($plan.originalSha256 -cnotmatch '^[a-f0-9]{64}$' -or $plan.resultSha256 -cnotmatch '^[a-f0-9]{64}$') {
      throw 'CODEX_INSTALL_INVALID_PLAN'
    }
    return $plan
  } catch { throw 'CODEX_INSTALL_INVALID_PLAN' }
  finally { if ($null -ne $document) { $document.Dispose() } }
}

function New-PrivateBackup([string]$Path, [byte[]]$Original) {
  $user = [System.Security.Principal.WindowsIdentity]::GetCurrent().User
  $system = [System.Security.Principal.SecurityIdentifier]::new('S-1-5-18')
  $security = [System.Security.AccessControl.FileSecurity]::new()
  $security.SetAccessRuleProtection($true, $false)
  $security.SetOwner($user)
  foreach ($identity in @($user, $system)) {
    $rule = [System.Security.AccessControl.FileSystemAccessRule]::new(
      $identity, [System.Security.AccessControl.FileSystemRights]::FullControl,
      [System.Security.AccessControl.AccessControlType]::Allow
    )
    $security.AddAccessRule($rule)
  }
  $file = [System.IO.FileSystemAclExtensions]::Create(
    [System.IO.FileInfo]::new($Path), [System.IO.FileMode]::CreateNew,
    [System.Security.AccessControl.FileSystemRights]::FullControl,
    [System.IO.FileShare]::None, 4096, [System.IO.FileOptions]::WriteThrough, $security
  )
  try {
    $file.Write($Original, 0, $Original.Length)
    $file.Flush($true)
    if ((Get-Sha256 (Read-StreamBytes $file $maximumConfigBytes)) -cne (Get-Sha256 $Original)) {
      throw 'CODEX_INSTALL_BACKUP_FAILED'
    }
  } finally { $file.Dispose() }
}

$configFile = $null
try {
  if (-not $IsWindows) { throw 'CODEX_INSTALL_WINDOWS_REQUIRED' }
  $plan = Read-Plan $PlanPath
  $configPath = Get-CheckedFilePath $plan.configPath
  if ([System.IO.Path]::GetFileName($configPath) -cne 'config.toml') { throw 'CODEX_INSTALL_INVALID_PATH' }
  $appendBytes = $utf8.GetBytes($plan.appendedText)
  if ($appendBytes.Length -gt $maximumAppendBytes) { throw 'CODEX_INSTALL_TOO_LARGE' }
  $access = if ($Apply) { [System.IO.FileAccess]::ReadWrite } else { [System.IO.FileAccess]::Read }
  $sharing = if ($Apply) { [System.IO.FileShare]::None } else { [System.IO.FileShare]::Read }
  $configFile = [System.IO.File]::Open($configPath, [System.IO.FileMode]::Open, $access, $sharing)
  $original = Read-StreamBytes $configFile $maximumConfigBytes
  if ((Get-Sha256 $original) -cne $plan.originalSha256) { throw 'CODEX_INSTALL_CONCURRENT_CHANGE' }
  $result = [byte[]]::new($original.Length + $appendBytes.Length)
  [System.Array]::Copy($original, 0, $result, 0, $original.Length)
  [System.Array]::Copy($appendBytes, 0, $result, $original.Length, $appendBytes.Length)
  if ((Get-Sha256 $result) -cne $plan.resultSha256) { throw 'CODEX_INSTALL_RESULT_MISMATCH' }
  if (-not $Apply -or $appendBytes.Length -eq 0) {
    $status = if ($Apply) { 'unchanged' } else { 'preview' }
    @{ status = $status; configPath = $configPath; originalSha256 = $plan.originalSha256; resultSha256 = $plan.resultSha256 } | ConvertTo-Json -Compress
    return
  }

  $backupPath = [System.IO.Path]::Combine(
    [System.IO.Path]::GetDirectoryName($configPath),
    ('config.toml.anysearch-backup-' + [System.Guid]::NewGuid().ToString('N') + '.bak')
  )
  New-PrivateBackup $backupPath $original
  try {
    $configFile.Position = $original.Length
    $configFile.Write($appendBytes, 0, $appendBytes.Length)
    $configFile.Flush($true)
    if ((Get-Sha256 (Read-StreamBytes $configFile ($maximumConfigBytes + $maximumAppendBytes))) -cne $plan.resultSha256) {
      throw 'CODEX_INSTALL_READBACK_MISMATCH'
    }
  } catch {
    # The exclusive handle prevents another writer; only our appended tail is removed.
    try { $configFile.SetLength($original.Length); $configFile.Flush($true) }
    catch { throw 'CODEX_INSTALL_ROLLBACK_FAILED' }
    throw 'CODEX_INSTALL_APPEND_FAILED'
  }
  @{ status = 'installed'; configPath = $configPath; backupPath = $backupPath; originalSha256 = $plan.originalSha256; resultSha256 = $plan.resultSha256 } | ConvertTo-Json -Compress
} catch {
  $code = $_.Exception.Message
  if ($code -cnotmatch '^CODEX_INSTALL_[A-Z_]+$') { $code = 'CODEX_INSTALL_IO_FAILED' }
  [Console]::Error.WriteLine($code)
  exit 1
} finally { if ($null -ne $configFile) { $configFile.Dispose() } }
